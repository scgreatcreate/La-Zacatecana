// Bakes the cup's printed wordmark ("La Zacatecana" / "Ice cream & Mex Snacks") from
// @fontsource/fredoka into SVG path data so the canvas decal never depends on runtime font
// loading (no FOUT, no network, crisp at any size). Run: node src/a-mangonada/hero/tools/gen-wordmark.mjs
import fs from 'node:fs';
import path from 'node:path';
import opentype from 'opentype.js';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '../../../..');
const font = (w) => opentype.parse(fs.readFileSync(path.join(root, `node_modules/@fontsource/fredoka/files/fredoka-latin-${w}-normal.woff`)).buffer);

function bake(f, text, size, letterSpacing = 0) {
  const p = f.getPath(text, 0, 0, size, { kerning: true, letterSpacing });
  const bb = p.getBoundingBox();
  // normalise so the path's bbox starts at 0,0
  for (const c of p.commands) {
    for (const k of ['x', 'x1', 'x2']) if (k in c) c[k] = +(c[k] - bb.x1).toFixed(0);
    for (const k of ['y', 'y1', 'y2']) if (k in c) c[k] = +(c[k] - bb.y1).toFixed(0);
  }
  return { d: p.toPathData(0), w: +(bb.x2 - bb.x1).toFixed(0), h: +(bb.y2 - bb.y1).toFixed(0), baseline: +(-bb.y1).toFixed(0) };
}

const out = {
  title: bake(font(700), 'La Zacatecana', 150, -0.01),
  sub: bake(font(500), 'Ice cream & Mex Snacks', 150, 0.01),
};
const file = path.join(root, 'src/a-mangonada/hero/wordmark-paths.js');
fs.writeFileSync(file, `// GENERATED by tools/gen-wordmark.mjs from @fontsource/fredoka (700 / 500). Do not edit.\nexport const WORDMARK = ${JSON.stringify(out)};\n`);
console.log(file, fs.statSync(file).size, 'bytes', out.title.w, out.title.h, out.sub.w, out.sub.h);
