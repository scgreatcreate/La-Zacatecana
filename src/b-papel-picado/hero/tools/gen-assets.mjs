// Dev-time generator (not shipped). Writes ../generated.js with:
//  - Lilita One glyph outlines for the letter flags (cut-out letters)
// Run: node src/b-papel-picado/hero/tools/gen-assets.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import opentype from 'opentype.js';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../../../..');
const fsrc = (pkg, file) => path.join(root, 'node_modules/@fontsource', pkg, 'files', file);
const load = (f) => { const b = fs.readFileSync(f); return opentype.parse(b.buffer.slice(b.byteOffset, b.byteOffset + b.byteLength)); };

const r = (n) => Math.round(n * 10) / 10;
function pathToD(p) {
  let d = '';
  for (const c of p.commands) {
    if (c.type === 'M' || c.type === 'L') d += c.type + r(c.x) + ' ' + r(c.y);
    else if (c.type === 'Q') d += 'Q' + r(c.x1) + ' ' + r(c.y1) + ' ' + r(c.x) + ' ' + r(c.y);
    else if (c.type === 'C') d += 'C' + r(c.x1) + ' ' + r(c.y1) + ' ' + r(c.x2) + ' ' + r(c.y2) + ' ' + r(c.x) + ' ' + r(c.y);
    else if (c.type === 'Z') d += 'Z';
  }
  return d.replace(/ -/g, '-');
}

// ---- Lilita One letters: one glyph per flag, at size 1000 (y down, baseline at 0)
const lilita = load(fsrc('lilita-one', 'lilita-one-latin-400-normal.woff'));
const letters = {};
for (const ch of 'LAZCTEN') {
  const p = lilita.getPath(ch, 0, 0, 1000);
  const bb = p.getBoundingBox();
  letters[ch] = { d: pathToD(p), x0: r(bb.x1), y0: r(bb.y1), x1: r(bb.x2), y1: r(bb.y2) };
}


const out = `// GENERATED by tools/gen-assets.mjs — do not edit by hand.
export const LETTERS = ${JSON.stringify(letters)};
`;
fs.writeFileSync(path.join(here, '../generated.js'), out);
console.log('generated.js', (out.length / 1024).toFixed(1) + ' kB');
