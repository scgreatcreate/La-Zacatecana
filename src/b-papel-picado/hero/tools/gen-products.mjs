// Dev-time: packs real product cutouts (assets/menu/hero/*) into one atlas for the counter,
// writing ../assets/products.webp and ../products.js (uv rects + aspect). Run after changing the list.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const sharp = createRequire(import.meta.url)('sharp');
const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../../../..');
// left → right on the counter; heights are the item's apparent height in metres
const ITEMS = [
  { file: 'fresas-con-crema-y-nutella.webp', h: 0.2, name: 'Fresas con crema' },
  { file: 'mangonada.webp', h: 0.34, name: 'Mangonada' },
  { file: 'esquite-con-hot-cheetos.webp', h: 0.24, name: 'Esquite con Hot Cheetos' },
  { file: 'sandifresa.webp', h: 0.36, name: 'Sandifresa' },
];
const SLOT_H = 480, PAD = 6;
const tiles = [];
for (const it of ITEMS) {
  const buf = await sharp(path.join(root, 'assets/menu/hero', it.file)).trim({ threshold: 2 }).resize({ height: SLOT_H - 2 * PAD }).png().toBuffer();
  const m = await sharp(buf).metadata();
  tiles.push({ ...it, buf, w: m.width, h0: m.height });
}
const W = tiles.reduce((a, t) => a + t.w + 2 * PAD, 0);
let x = 0;
const comps = [], rects = [];
for (const t of tiles) {
  comps.push({ input: t.buf, left: x + PAD, top: PAD });
  rects.push({ name: t.name, h: t.h, aspect: +(t.w / t.h0).toFixed(4), uv: [+((x + PAD) / W).toFixed(5), +(PAD / SLOT_H).toFixed(5), +(t.w / W).toFixed(5), +(t.h0 / SLOT_H).toFixed(5)] });
  x += t.w + 2 * PAD;
}
const out = path.resolve(here, '../assets/products.webp');
await sharp({ create: { width: W, height: SLOT_H, channels: 4, background: { r: 0, g: 0, b: 0, alpha: 0 } } })
  .composite(comps).webp({ quality: 78, alphaQuality: 85, effort: 6 }).toFile(out);
fs.writeFileSync(path.resolve(here, '../products.js'), `// GENERATED by tools/gen-products.mjs — uv rects (u0, v0 from top, du, dv) of assets/products.webp\nexport const PRODUCTS = ${JSON.stringify(rects)};\n`);
console.log('products.webp', W + 'x' + SLOT_H, (fs.statSync(out).size / 1024).toFixed(1) + ' kB');
