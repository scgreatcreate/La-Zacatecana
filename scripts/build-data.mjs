// Builds src/shared/menu-data.mjs from reference/menu.json (the single source of truth) + Spanish
// descriptions + the processed photo manifest + picture-menu crops. Run after process-photos.
import fs from 'node:fs';
import path from 'node:path';
import sharp from 'sharp';
import { DESC_ES } from '../src/shared/menu-es.mjs';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const menu = JSON.parse(fs.readFileSync(path.join(root, 'reference/menu.json'), 'utf8'));
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'assets/menu/manifest.json'), 'utf8'));
const pmPath = path.join(root, 'assets/menu/picture-menu-crops.json');
const pm = fs.existsSync(pmPath) ? JSON.parse(fs.readFileSync(pmPath, 'utf8')) : {};

export const slugify = (s) => s.normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

// average colour of opaque pixels → per-card tint
async function tint(slug) {
  const w = manifest[slug]?.widths?.[0];
  if (!w) return null;
  const { data, info } = await sharp(path.join(root, 'assets/menu/web', `${slug}-${w}.webp`)).resize(48, 48).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  let r = 0, g = 0, b = 0, n = 0;
  for (let i = 0; i < info.width * info.height; i++) {
    const a = data[i * 4 + 3]; if (a < 200) continue;
    r += data[i * 4]; g += data[i * 4 + 1]; b += data[i * 4 + 2]; n++;
  }
  if (!n) return null;
  return [r / n, g / n, b / n].map((v) => Math.round(v));
}

const seen = new Set();
const items = [];
const missingEs = [];
for (const [i, it] of menu.items.entries()) {
  let slug = slugify(it.name_es);
  if (seen.has(slug)) slug = `${slug}-${i}`;
  seen.add(slug);
  const photo = manifest[slug] ? { widths: manifest[slug].widths, side: manifest[slug].side } : null;
  if (it.description_en && !DESC_ES[it.name_es]) missingEs.push(it.name_es);
  items.push({
    id: slug,
    n: it.menu_number,
    es: it.name_es,
    en: it.name_en,
    price: it.price_usd,
    cat: it.category,
    tags: it.tags || [],
    dEn: it.description_en || null,
    dEs: it.description_en ? DESC_ES[it.name_es] || null : null,
    photo,
    tint: photo ? await tint(slug) : null,
    pm: pm[slug] || null, // small crop from the owner's in-store picture menu (shown ≤ half native size)
    confirm: it.confirm_with_owner || null,
  });
}
if (missingEs.length) console.warn('Missing Spanish description for:', missingEs);

const out = `// GENERATED by scripts/build-data.mjs from reference/menu.json — do not edit by hand.
export const CATEGORIES = ${JSON.stringify(menu.categories)};
export const ITEMS = ${JSON.stringify(items)};
`;
fs.writeFileSync(path.join(root, 'src/shared/menu-data.mjs'), out);
console.log('items', items.length, 'with photo', items.filter((x) => x.photo).length, 'with pm crop', items.filter((x) => x.pm).length);
