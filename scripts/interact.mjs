// Interaction smoke test: language toggle, mood chips, search, "See all", slot machine, order hrefs.
import { chromium } from 'playwright';
import path from 'node:path'; import fs from 'node:fs';
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const dir = process.argv[2] || 'a-mangonada';
const out = path.join(root, 'review', dir); fs.mkdirSync(out, { recursive: true });
const browser = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, locale: 'es-MX' });
const errs = []; page.on('pageerror', (e) => errs.push(e.message));
await page.goto('file://' + path.join(root, 'directions', dir, 'index.html') + '?static');
await page.waitForTimeout(500);
const r = {};
r.langDefaultEs = await page.evaluate(() => document.documentElement.lang);
r.orderLabelEs = await page.textContent('.site-header .btn-order');
await page.click('[data-lang="en"]');
r.orderLabelEn = await page.textContent('.site-header .btn-order');
r.stored = await page.evaluate(() => localStorage.getItem('lz-lang'));
await page.click('.chip[data-mood="picante"]');
r.picante = await page.textContent('[data-result-count]');
await page.click('.chip[data-mood="dulce"]');
r.dulcePicante = await page.textContent('[data-result-count]');
await page.click('[data-clear]');
await page.fill('[data-search]', 'takis');
await page.waitForTimeout(200);
r.searchTakis = await page.textContent('[data-result-count]');
r.searchTakisNames = await page.$$eval('.mcard:not([hidden]) .mcard__name', (els) => els.map((e) => e.textContent));
await page.fill('[data-search]', '');
await page.waitForTimeout(200);
r.hiddenByCollapse = await page.$$eval('.mcard', (els) => els.filter((e) => getComputedStyle(e).display === 'none').length);
await page.locator('[data-machine]').scrollIntoViewIfNeeded();
await page.click('[data-spin]');
await page.waitForTimeout(3600);
r.machine = await page.textContent('[data-machine-name]');
r.machineHref = await page.getAttribute('[data-machine-order]', 'href');
await page.locator('[data-machine]').screenshot({ path: path.join(out, 'machine-m.png') });
r.orderHrefs = [...new Set(await page.$$eval('[data-order]', (els) => els.map((e) => e.getAttribute('data-order') + ' → ' + e.href)))];
r.errors = errs;
console.log(JSON.stringify(r, null, 1));
await browser.close();
